#!/usr/bin/env python3
"""Convert a CUPL .tt2 (Berkeley PLA) netlist into "gold" Verilog with the split pin interface.

  python3 tools/sim/tt2v.py design.tt2 [--fit design.fit] [-o gold.v] [--module gold]

The module has the same ports as the Verilog that `atf15xx-sim verilog` emits for a JED, for
the pins the design uses: `input pN_in` (external level) for every placed pin, and
`output pN_oe` / `output pN_out` (masked: oe & value) for every placed output. So
`tools/sim/equiv.py --tt2` can compare a fitted JED against its .tt2 pin by pin.

Pin placement: `NAME is placed at pin N` / `NAME assigned to pin N` lines of the .fit report
(the fitter's choice), else the `#$ PINS` line of the .tt2 (CUPL pin assignments).
Open-collector outputs: `-open_collector a,b` on the fitter command line in the .fit
(or --open-collector).

Semantics (the CUPL meaning; docs/architecture/sim/03-equivalence.md):
* outputs `X` (combinational), `X.D`/`X.REG` (D flip-flop), `X.T` (T flip-flop), `X.L` (latch) with
  `X.C` (clock), `X.LE` (latch enable), `X.CE` (clock enable), `X.AR`, `X.AP` (async reset /
  preset; reset wins), `X.OE` (output enable; a missing or empty OE cover = always enabled);
  a trailing `-` or a `.phase` 0 complements that function;
* inputs `X.Q` (register output), `X.PIN` (the pin), `X` (a pin, or a node's value);
* registers power up 0 (as the device, docs/architecture/fitter/02-fuse-map.md §F2.8 [I]);
* a register without a `.C` never clocks.
"""
import argparse, os, re, sys

SUFFIX_REG = ('D', 'REG', 'T', 'L')


def parse_tt2(text):
    lines = [l.strip() for l in text.replace('\r', '').split('\n')]
    ilb = next(l.split()[1:] for l in lines if l.startswith('.ilb'))
    ob = next(l.split()[1:] for l in lines if l.startswith('.ob'))
    ph = next((l.split()[1] for l in lines if l.startswith('.phase')), '1' * len(ob))
    cubes = [l.split() for l in lines if l and l[0] in '01-' and len(l.split()) == 2]
    pins = {}
    for l in lines:
        if l.startswith('#$ PINS'):
            for t in l.split()[3:]:
                m = re.match(r'(\S+?)[+-]?:(\d+)$', t)
                if m:
                    pins[m.group(1)] = int(m.group(2))
    return ilb, ob, ph, cubes, pins


def fit_info(fit_text):
    place = {}
    for m in re.finditer(r'^(\S+) (?:is placed at pin|assigned to pin)\s+(\d+)', fit_text.replace('\r', ''), re.M):
        place[m.group(1)] = int(m.group(2))
    oc = []
    m = re.search(r'-open_collector\s+(?:=\s*)?([^\r\n-][^\r\n]*?)(?:\s+-|\r|\n)', fit_text)
    if m and m.group(1).strip().lower() not in ('on', 'off'):
        oc = m.group(1).replace(',', ' ').split()
    return place, oc


def vname(s):
    return 'n_' + re.sub(r'[^A-Za-z0-9_]', '_', s)


def convert(tt2_text, place, open_collector=(), module='gold'):
    ilb, ob, ph, cubes, tt2pins = parse_tt2(tt2_text)
    if not place:
        place = {k: v for k, v in tt2pins.items() if v}
    f = {}                                    # (base, SUFFIX) -> (output index, complemented)
    for i, o in enumerate(ob):
        low = o.endswith('-') ^ (ph[i] == '0') if i < len(ph) else o.endswith('-')
        base, _, suf = o.rstrip('-').partition('.')
        f[(base, suf.upper())] = (i, low)
    cells = sorted({b for b, _ in f})

    def kind(c):
        return next((s for s in SUFFIX_REG if (c, s) in f), '')

    def cover(i):
        terms = []
        for cube, outs in cubes:
            if outs[i] != '1':
                continue
            lits = []
            for j, ch in enumerate(cube):
                if ch == '-':
                    continue
                lits.append(('' if ch == '1' else '~') + vname(ilb[j]))
            terms.append('(' + (' & '.join(lits) if lits else "1'b1") + ')')
        return terms

    def fn(c, suf, default=None):
        if (c, suf) not in f:
            return default
        i, low = f[(c, suf)]
        t = cover(i)
        if suf == 'OE' and not t:
            return default        # vendor quirk: an OE with an empty cover means "always enabled"
        e = ' | '.join(t) if t else "1'b0"
        return ('~(%s)' % e) if low else e

    v = ['// Generated by tools/sim/tt2v.py (gold model of a .tt2; split pin interface).']
    ports, body = [], []
    placed = {c: p for c, p in place.items()}
    outs = [c for c in cells if c in placed]
    ins = sorted({placed[n] for n in placed})
    for p in ins:
        ports.append('input wire p%d_in' % p)
    for c in outs:
        ports.append('output wire p%d_oe' % placed[c])
        ports.append('output wire p%d_out' % placed[c])
    v.append('module %s (\n  %s\n);' % (module, ',\n  '.join(ports)))
    # literal nets
    declared = set()
    for l in ilb:
        n, _, suf = l.partition('.')
        w = vname(l)
        if w in declared:
            continue
        declared.add(w)
        if suf == 'Q' or (n in cells and kind(n) and suf == ''):
            src = 'q_' + vname(n)
        elif suf == 'PIN' or n not in cells:
            src = ('pad_' + vname(n)) if n in outs else ('p%d_in' % placed[n] if n in placed else "1'b0")
        else:
            src = 'comb_' + vname(n)
        body.append('  wire %s = %s;' % (w, src))
    oc = set(open_collector)
    for c in cells:
        k = kind(c)
        cv = vname(c)
        if k:
            d = fn(c, k, "1'b0")
            clk = fn(c, 'LE' if k == 'L' else 'C', "1'b0")
            ce = fn(c, 'CE')
            ar = fn(c, 'AR')
            ap = fn(c, 'AP')
            body.append('  wire d_%s = %s;' % (cv, d))
            body.append('  wire clk_%s = %s;' % (cv, clk))
            prio = []
            if ar:
                body.append('  wire ar_%s = %s;' % (cv, ar))
                prio.append(('ar_' + cv, "1'b0"))
            if ap:
                body.append('  wire ap_%s = %s;' % (cv, ap))
                prio.append(('ap_' + cv, "1'b1"))
            pre = ''.join('if (%s) q_%s <= %s; else ' % (s, cv, val) for s, val in prio)
            body.append("  reg q_%s = 1'b0;" % cv)
            if k == 'L':
                body.append('  always @* %sif (clk_%s) q_%s <= d_%s;' % (pre, cv, cv, cv))
            else:
                load = ('q_%s <= q_%s ^ d_%s;' if k == 'T' else 'q_%s <= d_%s;') % ((cv, cv, cv) if k == 'T' else (cv, cv))
                if ce:
                    load = 'if (%s) %s' % (ce, load)
                sens = ['posedge clk_' + cv] + ['posedge ' + s for s, _ in prio]
                body.append('  always @(%s) %s%s' % (' or '.join(sens), pre, load))
            val = 'q_' + cv
        else:
            body.append('  wire comb_%s = %s;' % (cv, fn(c, '', "1'b0")))
            val = 'comb_' + cv
        if c in placed:
            p = placed[c]
            en = fn(c, 'OE', "1'b1")
            if c in oc:
                body.append('  wire en_%s = (%s) & ~%s;' % (cv, en, val))
                body.append("  wire o_%s = 1'b0;" % cv)
            else:
                body.append('  wire en_%s = %s;' % (cv, en))
                body.append('  wire o_%s = %s;' % (cv, val))
            body.append('  wire pad_%s = en_%s ? o_%s : p%d_in;' % (cv, cv, cv, p))
            body.append('  assign p%d_oe = en_%s;' % (p, cv))
            body.append('  assign p%d_out = en_%s & o_%s;' % (p, cv, cv))
    # declare forward-referenced nets first (Verilog needs declarations before use in some tools)
    decls = []
    for c in cells:
        cv = vname(c)
        if kind(c):
            pass
        else:
            decls.append('  wire comb_%s;' % cv)
        if c in placed:
            decls.append('  wire pad_%s;' % cv)
    body = [re.sub(r'^  wire (comb_\S+|pad_\S+) = ', r'  assign \1 = ', l) for l in body]
    v += decls
    # registers are declared in body; move their declarations first too
    regs = [l for l in body if l.startswith('  reg ')]
    rest = [l for l in body if not l.startswith('  reg ')]
    v += regs + rest
    v.append('endmodule')
    return '\n'.join(v) + '\n', placed, outs


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('tt2')
    ap.add_argument('--fit', help='fitter report with the pin placement (default: the .tt2 PINS line)')
    ap.add_argument('--open-collector', default='', help='comma-separated open-collector outputs (default: from the .fit)')
    ap.add_argument('--module', default='gold')
    ap.add_argument('-o', '--output', help='output file (default: stdout)')
    a = ap.parse_args()
    place, oc = ({}, [])
    if a.fit:
        place, oc = fit_info(open(a.fit, errors='replace').read())
    if a.open_collector:
        oc = [x for x in a.open_collector.split(',') if x]
    text, _, _ = convert(open(a.tt2, errors='replace').read(), place, oc, a.module)
    if a.output:
        open(a.output, 'w').write(text)
    else:
        sys.stdout.write(text)


if __name__ == '__main__':
    main()
