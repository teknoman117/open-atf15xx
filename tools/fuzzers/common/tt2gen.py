"""Write CUPL-style Berkeley PLA (.tt2) files for fitter experiments.

A design is described by:
  device   e.g. 'f1504plcc44' (written to #$ DEVICE)
  pins     [(name, pin_number or None)]       -> #$ PINS
  nodes    [name]                              -> #$ NODES
  inputs   list of .ilb names (e.g. 'A', 'Q1.Q', 'D0.PIN')
  outputs  list of .ob names (e.g. 'Y', 'Q1.REG', 'Q1.C', 'Y-' for active-low)
  terms    list of (cube, set_of_output_indices); cube is a string over inputs of '0','1','-'
  props    list of '#$ PROPERTY ATMEL ...' tails
"""


def write_tt2(path, name, device, pins, nodes, inputs, outputs, terms, props=()):
    lines = ['#$ TOOL CUPL', '# Berkeley PLA format generated by open-atf150x tt2gen', '#$ TITLE  ' + name,
             '#$ MODULE  ' + name, '#$ JEDECFILE  ' + name, '#$ DEVICE  ' + device]
    for p in props:
        lines.append('#$ PROPERTY ATMEL ' + p)
    lines.append('#$ PINS  %d %s ' % (len(pins), ' '.join('%s+%s' % (n, (':%d' % p) if p else '') for n, p in pins)))
    if nodes:
        lines.append('#$ NODES %d %s ' % (len(nodes), ' '.join(n + '+' for n in nodes)))
    lines += ['.i %d' % len(inputs), '.o %d' % len(outputs), '.type f', '.ilb  ' + ' '.join(inputs) + ' ',
              '.ob   ' + ' '.join(outputs) + ' ', '.phase ' + '1' * len(outputs), '.p %d' % len(terms)]
    for cube, outs in terms:
        assert len(cube) == len(inputs)
        lines.append(cube + ' ' + ''.join('1' if i in outs else '0' for i in range(len(outputs))))
    lines.append('.e')
    with open(path, 'w', newline='\r\n') as f:
        f.write('\n'.join(lines) + '\n')


def cube(inputs, lits):
    """lits: {input_name: '0'|'1'} -> cube string."""
    return ''.join(lits.get(n, '-') for n in inputs)
