//! Generates atf15xx-arch's tables at build time; nothing here is read at run time.
//!
//! * the fuse map of each family, from prjbureau's `database.json` (the submodule
//!   `external/prjbureau`, or `$ATF15XX_PRJBUREAU`);
//! * the boundary register of each part, from prjbureau's Atmel BSDL files (`bsdl/`);
//! * the devices (`data/devices.json`) and the speed-grade tables (`data/timing.json`), our own
//!   data from the black-box workflows in `tools/fuzzers/`.
//!
//! prjbureau's files are not copied into this repository; only the generated Rust (in `OUT_DIR`)
//! is compiled in.

mod bsdl;
mod devices;
mod fuse_map;
#[path = "../src/layout.rs"]
mod layout;
mod timing;

use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let prjbureau = std::env::var_os("ATF15XX_PRJBUREAU").map(PathBuf::from).unwrap_or_else(|| manifest.join("../external/prjbureau"));
    let database = prjbureau.join("database.json");
    let bsdl_dir = prjbureau.join("bsdl");
    let devices_json = manifest.join("data/devices.json");
    let timing_json = manifest.join("data/timing.json");
    for p in [&database, &bsdl_dir, &devices_json, &timing_json] {
        println!("cargo:rerun-if-changed={}", p.display());
    }
    println!("cargo:rerun-if-env-changed=ATF15XX_PRJBUREAU");
    let read = |p: &PathBuf| {
        std::fs::read_to_string(p).unwrap_or_else(|e| {
            panic!("{}: {e}\n(prjbureau is the git submodule external/prjbureau: run `git submodule update --init`)", p.display())
        })
    };

    // fuse map
    let db: serde_json::Value = serde_json::from_str(&read(&database)).expect("prjbureau database.json");
    let (reference, rproblems) = fuse_map::family(&db["ATF1504AS"], "1504");
    assert!(rproblems.is_empty(), "prjbureau ATF1504AS: {rproblems:#?}");
    let mut fams = vec![];
    for (dev, num) in [("ATF1502AS", "1502"), ("ATF1504AS", "1504"), ("ATF1508AS", "1508")] {
        assert!(db.get(dev).is_some(), "prjbureau database.json has no {dev} (is the submodule at the pinned commit?)");
        let (mut f, problems) = fuse_map::family(&db[dev], num);
        let mut problems: Vec<String> = problems.into_iter().filter(|p| !p.contains("not determined")).collect();
        fuse_map::infer_fields(&mut f, &reference, &mut problems);
        assert!(problems.is_empty(), "prjbureau {dev}: {problems:#?}");
        fams.push(f);
    }

    // devices, timing, boundary scan
    let devs = devices::load(&read(&devices_json));
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let header = "// @generated by atf15xx-arch/build/main.rs; do not edit.\n";
    std::fs::write(out.join("fuse_map.rs"), format!("{header}{}", fuse_map::emit(&fams))).unwrap();
    std::fs::write(out.join("devices.rs"), format!("{header}{}", devices::emit(&devs))).unwrap();
    std::fs::write(out.join("timing.rs"), format!("{header}{}", timing::emit(&read(&timing_json)))).unwrap();
    std::fs::write(out.join("bsdl.rs"), format!("{header}{}", bsdl::emit(&bsdl_dir, &devs))).unwrap();
}
