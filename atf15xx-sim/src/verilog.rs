//! JED → synthesizable Verilog (docs/architecture/sim/02-verilog.md).
//!
//! The core module has a *split* pin interface that is convenient for formal equivalence and
//! co-simulation: for every pin `N`, `input pN_in` (the external level); for every I/O pin also
//! `output pN_oe` (the device drives the pin) and `output pN_out` (the driven value, forced to 0
//! when `pN_oe` is 0, so disabled outputs compare equal). An optional wrapper module exposes the
//! same design with real `inout pN` / `input pN` ports for board-level simulation.

use crate::model::{Clock, Lit, Mc, Model, Oe, PinKind, Sig};
use atf15xx_arch::decode::{DSource, PtUse, Storage};
use std::fmt::Write as _;

pub struct EmitOptions {
    pub module: String,
    /// Also emit `<module>_pins` with `inout`/`input` ports.
    pub pins_wrapper: bool,
}

fn b(v: bool) -> &'static str {
    if v {
        "1'b1"
    } else {
        "1'b0"
    }
}

fn sig(s: Sig) -> String {
    match s {
        Sig::Const(v) => b(v).into(),
        Sig::Pad(m) => format!("pad_{m}"),
        Sig::Fb(m) => format!("fb_{m}"),
        Sig::Pin(p) => format!("p{p}_in"),
    }
}

fn pt_expr(mc: &Mc, k: usize) -> String {
    match &mc.pts[k] {
        None => "1'b0".into(),
        Some(l) if l.is_empty() => "1'b1".into(),
        Some(lits) => lits
            .iter()
            .map(|l| match *l {
                Lit::Sig(s, true) => sig(s),
                Lit::Sig(s, false) => format!("~{}", sig(s)),
                Lit::Fold(h) => format!("fold_{h}"),
            })
            .collect::<Vec<_>>()
            .join(" & "),
    }
}

/// Emit the model as Verilog.
pub fn emit(m: &Model, o: &EmitOptions) -> String {
    let mut v = String::new();
    let dev = m.device;
    writeln!(v, "// Generated by atf15xx-sim from a {} fuse map for device {} ({}).", m.family, dev.name, dev.package).unwrap();
    writeln!(
        v,
        "// Semantics: docs/architecture/fitter/02-fuse-map.md §F2.8; options: reset_wins={} power_up={} cascade_requires_pts={} lender_a_is_one={} idle_mc_holds={} oe_pt5_needs_mux={}",
        m.opts.reset_wins,
        if m.opts.power_up_from_fuse { "fuse".to_string() } else { (m.opts.power_up as u8).to_string() },
        m.opts.cascade_requires_pts, m.opts.lender_a_is_one, m.opts.idle_mc_holds, m.opts.oe_pt5_needs_mux
    )
    .unwrap();
    writeln!(v, "// JTAG port {}; pins: {}", if m.decoded.jtag { "enabled (JTAG pins omitted)" } else { "disabled" }, m.pins.len()).unwrap();
    let mut ports = vec![];
    for &(p, k) in &m.pins {
        ports.push(format!("input wire p{p}_in"));
        if let PinKind::Io(_) = k {
            ports.push(format!("output wire p{p}_oe"));
            ports.push(format!("output wire p{p}_out"));
        }
    }
    writeln!(v, "module {} (\n  {}\n);", o.module, ports.join(",\n  ")).unwrap();
    // global networks
    for n in 0..3 {
        let (s, inv) = m.gclk[n];
        writeln!(v, "  wire gclk{} = {}{};", n + 1, sig(s), if inv { " ^ 1'b1" } else { "" }).unwrap();
    }
    writeln!(v, "  wire gclr = {}{};", sig(m.gclr.0), if m.gclr.1 { " ^ 1'b1" } else { "" }).unwrap();
    for n in 0..6 {
        let (s, inv) = m.goe[n];
        writeln!(v, "  wire goe{} = {}{};", n + 1, sig(s), if inv { " ^ 1'b1" } else { "" }).unwrap();
    }
    // declarations
    for mc in &m.mcs {
        let i = mc.mc;
        writeln!(v, "  wire pad_{i}, fb_{i}, x_{i}, sum_{i}, fold_{i};").unwrap();
    }
    for mc in &m.mcs {
        let i = mc.mc;
        let used = mc.has_pts() || mc.cascade_out || mc.oe != Oe::Never || mc.pin.is_some();
        if !used {
            writeln!(v, "  // MC{i}: unused").unwrap();
        } else {
            writeln!(
                v,
                "  // MC{i} (block {}, local {}){}: storage={:?} d={:?} clock={:?} oe={:?}{}{}",
                atf15xx_arch::block_letter(mc.block),
                mc.local,
                mc.pin.map(|p| format!(" pin {p}")).unwrap_or_default(),
                mc.storage,
                mc.d_source,
                mc.clock,
                mc.oe,
                if mc.open_drain { " open-drain" } else { "" },
                if mc.cascade_out { " cascade-out" } else { "" }
            )
            .unwrap();
        }
        for k in 0..5 {
            if mc.pts[k].is_some() {
                writeln!(v, "  wire pt{}_{i} = {}; // {:?}", k + 1, pt_expr(mc, k), mc.pt_use[k]).unwrap();
            }
        }
        let ptw = |k: usize| if mc.pts[k].is_some() { format!("pt{}_{i}", k + 1) } else { "1'b0".into() };
        // foldback line hosted here
        if mc.pt_use[0] == PtUse::Foldback {
            writeln!(v, "  assign fold_{i} = ~{};", ptw(0)).unwrap();
        } else {
            writeln!(v, "  assign fold_{i} = 1'b1;").unwrap();
        }
        let mut terms: Vec<String> = (0..5).filter(|&k| mc.pt_use[k] == PtUse::Sum && mc.pts[k].is_some()).map(ptw).collect();
        if mc.cascade_in {
            terms.push(format!("sum_{}", i - 1));
        }
        writeln!(v, "  assign sum_{i} = {};", if terms.is_empty() { "1'b0".into() } else { terms.join(" | ") }).unwrap();
        // XOR (F2.8 row 6): P = PT2 if Pt2Mux else 1; A = CasMux ? P : sum; B = Invert & (CasMux ? 1 : P)
        let p = if mc.xor_pt2 { ptw(1) } else { "1'b1".into() };
        if mc.const_one {
            writeln!(v, "  assign x_{i} = 1'b1; // CasMux without PTs").unwrap();
        } else if mc.a_is_one {
            writeln!(v, "  assign x_{i} = {p} ^ {};", b(mc.invert)).unwrap();
        } else if mc.invert {
            writeln!(v, "  assign x_{i} = sum_{i} ^ {p};").unwrap();
        } else {
            writeln!(v, "  assign x_{i} = sum_{i};").unwrap();
        }
        // register
        if mc.active {
            let d = match mc.d_source {
                DSource::Logic if mc.storage == Storage::TFlipFlop => format!("x_{i} ^ q_{i}"),
                DSource::Logic => format!("x_{i}"),
                DSource::Pt2 => ptw(1),
                DSource::Pad => format!("pad_{i}"),
            };
            let clk = match mc.clock {
                Clock::Pt4 => ptw(3),
                Clock::High => "1'b1".into(),
                Clock::Global(n) => format!("gclk{n}"),
            };
            let ce = if mc.ce_pt4 { ptw(3) } else { "1'b1".into() };
            let mut ar = vec![];
            if mc.ar_pt3 {
                ar.push(ptw(2));
            }
            if mc.ar_gclr {
                ar.push("gclr".into());
            }
            let ar = if ar.is_empty() { None } else { Some(ar.join(" | ")) };
            let ap = if mc.ap_pt5 { Some(ptw(4)) } else { None };
            writeln!(v, "  wire d_{i} = {d};").unwrap();
            writeln!(v, "  wire clk_{i} = {clk};").unwrap();
            if let Some(a) = &ar {
                writeln!(v, "  wire ar_{i} = {a};").unwrap();
            }
            if let Some(a) = &ap {
                writeln!(v, "  wire ap_{i} = {a};").unwrap();
            }
            let pu = b(mc.init);
            let mut prio: Vec<(String, &str)> = vec![];
            if ar.is_some() {
                prio.push((format!("ar_{i}"), "1'b0"));
            }
            if ap.is_some() {
                prio.push((format!("ap_{i}"), "1'b1"));
            }
            if !m.opts.reset_wins {
                prio.reverse();
            }
            let mut body = String::new();
            for (s, val) in &prio {
                write!(body, "if ({s}) q_{i} <= {val}; else ").unwrap();
            }
            if mc.storage == Storage::Latch {
                // non-blocking: the latch output changes after every flip-flop clocked by the
                // same edge has sampled its D (clock-to-output delay; matches sim.rs)
                writeln!(v, "  reg q_{i} = {pu};").unwrap();
                writeln!(v, "  always @* {body}if (clk_{i}) q_{i} <= d_{i};").unwrap();
            } else if mc.clock == Clock::High && prio.is_empty() {
                // clock tied high: the flip-flop never loads
                writeln!(v, "  reg q_{i} = {pu};").unwrap();
            } else {
                writeln!(v, "  reg q_{i} = {pu};").unwrap();
                let mut sens = if mc.clock == Clock::High { vec![] } else { vec![format!("posedge clk_{i}")] };
                for (s, _) in &prio {
                    sens.push(format!("posedge {s}"));
                }
                let ce_s = if mc.ce_pt4 { format!("if ({ce}) ") } else { String::new() };
                let load = if mc.clock == Clock::High { format!("q_{i} <= q_{i};") } else { format!("{ce_s}q_{i} <= d_{i};") };
                writeln!(v, "  always @({}) {body}{load}", sens.join(" or ")).unwrap();
            }
        } else {
            writeln!(v, "  wire q_{i} = {};", b(mc.init)).unwrap();
        }
        writeln!(v, "  assign fb_{i} = {};", if mc.fb_comb { format!("x_{i}") } else { format!("q_{i}") }).unwrap();
        // pin
        if let Some(p) = mc.pin {
            let o = if mc.out_comb { format!("x_{i}") } else { format!("q_{i}") };
            let en = match mc.oe {
                Oe::Never => "1'b0".to_string(),
                Oe::Always => "1'b1".to_string(),
                Oe::Pt5 => ptw(4),
                Oe::Global(n) => format!("goe{n}"),
            };
            if mc.open_drain {
                writeln!(v, "  wire drv_en_{i} = ({en}) & ~{o};").unwrap();
                writeln!(v, "  wire drv_v_{i} = 1'b0;").unwrap();
            } else {
                writeln!(v, "  wire drv_en_{i} = {en};").unwrap();
                writeln!(v, "  wire drv_v_{i} = {o};").unwrap();
            }
            writeln!(v, "  assign pad_{i} = drv_en_{i} ? drv_v_{i} : p{p}_in;").unwrap();
            writeln!(v, "  assign p{p}_oe = drv_en_{i};").unwrap();
            writeln!(v, "  assign p{p}_out = drv_en_{i} & drv_v_{i};").unwrap();
        } else if let Some(&(p, _)) = m.pins.iter().find(|&&(_, k)| k == PinKind::InputOnly(i)) {
            writeln!(v, "  assign pad_{i} = p{p}_in;").unwrap();
        } else {
            writeln!(v, "  assign pad_{i} = 1'b0;").unwrap();
        }
    }
    // I/O pins whose macrocell is not modelled cannot exist (every I/O pin has an MC).
    writeln!(v, "endmodule").unwrap();
    if o.pins_wrapper {
        let mut ports = vec![];
        let mut body = String::new();
        let mut conns = vec![];
        for &(p, k) in &m.pins {
            match k {
                PinKind::Io(_) => {
                    ports.push(format!("inout wire p{p}"));
                    writeln!(body, "  wire p{p}_oe, p{p}_out;\n  assign p{p} = p{p}_oe ? p{p}_out : 1'bz;").unwrap();
                    conns.push(format!(".p{p}_in(p{p}), .p{p}_oe(p{p}_oe), .p{p}_out(p{p}_out)"));
                }
                _ => {
                    ports.push(format!("input wire p{p}"));
                    conns.push(format!(".p{p}_in(p{p})"));
                }
            }
        }
        writeln!(v, "\n// Board-level wrapper with real pins.\nmodule {}_pins (\n  {}\n);", o.module, ports.join(",\n  ")).unwrap();
        v.push_str(&body);
        writeln!(v, "  {} core (\n    {}\n  );\nendmodule", o.module, conns.join(",\n    ")).unwrap();
    }
    v
}

/// Human-readable equations of every used macrocell.
pub fn equations(m: &Model) -> String {
    let mut s = String::new();
    writeln!(s, "device {} ({}), JTAG {}", m.device.name, m.family, if m.decoded.jtag { "on" } else { "off" }).unwrap();
    for (n, (src, inv)) in m.gclk.iter().enumerate() {
        writeln!(s, "GCLK{} = {}{}", n + 1, if *inv { "!" } else { "" }, sig(*src)).unwrap();
    }
    writeln!(s, "GCLR = {}{}", if m.gclr.1 { "!" } else { "" }, sig(m.gclr.0)).unwrap();
    for (n, (src, inv)) in m.goe.iter().enumerate() {
        if *src != Sig::Const(false) || *inv {
            writeln!(s, "GOE{} = {}{}", n + 1, if *inv { "!" } else { "" }, sig(*src)).unwrap();
        }
    }
    for mc in m.used_mcs() {
        writeln!(
            s,
            "MC{}{}: {:?} d={:?} clk={:?} oe={:?} out={} fb={}{}{}{}",
            mc.mc,
            mc.pin.map(|p| format!(" (pin {p})")).unwrap_or_default(),
            mc.storage,
            mc.d_source,
            mc.clock,
            mc.oe,
            if mc.out_comb { "x" } else { "q" },
            if mc.fb_comb { "x" } else { "q" },
            if mc.invert { " invert" } else { "" },
            if mc.cascade_out { " cascade-out" } else { "" },
            if mc.open_drain { " open-drain" } else { "" }
        )
        .unwrap();
        for k in 0..5 {
            if mc.pts[k].is_some() {
                writeln!(s, "    PT{} [{:?}] = {}", k + 1, mc.pt_use[k], pt_expr(mc, k)).unwrap();
            }
        }
    }
    s
}
